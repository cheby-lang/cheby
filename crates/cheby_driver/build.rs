//! Computes the source hashes of the standard library's modules (D-963,
//! D-538) and writes `$OUT_DIR/std_hashes.rs`, which `src/std_lib.rs`
//! includes.
//!
//! Std's sources are embedded in `cheby` (D-450), so their hashes are
//! computed once, here, when `cheby` is built, never per command (D-963).
//! Each module gets two hashes of its file's bytes, both SipHash-1-3 with
//! zero keys (GAP(source-hash-width)): the 128-bit one that the cache's
//! keys use (D-956), and the 64-bit one of D-538 that constant seeds use.
//! The inputs are every `.cheby` file under `std/` at the workspace root,
//! the files `src/std_lib.rs` embeds (a test of `std_lib` checks that the
//! lists agree, and another that every constant equals the hash of the
//! embedded text). Module paths are the files' paths under `std/` without
//! the extension, with `::` between segments, sorted.

use std::env;
use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::hash::Hasher as _;
use std::path::{Path, PathBuf};

use siphasher::sip::SipHasher13 as Sip64;
use siphasher::sip128::{Hasher128 as _, SipHasher13 as Sip128};

fn main() -> Result<(), Box<dyn Error>> {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR")?);
    let std_dir = manifest.join("../../std");
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-changed={}", std_dir.display());
    let mut modules = Vec::new();
    collect(&std_dir, "", &mut modules)?;
    modules.sort();
    let mut out = String::from(
        "/// Generated by `build.rs`: per std module, sorted by path, its path\n\
         /// under `std`, the SipHash-1-3 128 and the SipHash-1-3 64 with zero keys\n\
         /// of its source file's bytes (D-963, D-538).\n\
         pub(crate) const STD_SOURCE_HASHES: &[(&str, [u8; 16], u64)] = &[\n",
    );
    for (path, file) in &modules {
        let bytes = fs::read(file)?;
        let mut wide = Sip128::new_with_keys(0, 0);
        wide.write(&bytes);
        let wide = wide.finish128().as_bytes();
        let mut narrow = Sip64::new_with_keys(0, 0);
        narrow.write(&bytes);
        let narrow = narrow.finish().to_le_bytes();
        writeln!(
            out,
            "    ({path:?}, {wide:?}, u64::from_le_bytes({narrow:?})),"
        )?;
    }
    out.push_str("];\n");
    let dest = PathBuf::from(env::var("OUT_DIR")?).join("std_hashes.rs");
    fs::write(dest, out)?;
    Ok(())
}

/// Every `.cheby` file under `dir`, as (module path, file), with `prefix`
/// before each path.
fn collect(
    dir: &Path,
    prefix: &str,
    out: &mut Vec<(String, PathBuf)>,
) -> Result<(), Box<dyn Error>> {
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        let Some(name) = path.file_name().and_then(|n| n.to_str()).map(str::to_owned) else {
            continue;
        };
        if name.starts_with('.') {
            continue;
        }
        if path.is_dir() {
            collect(&path, &format!("{prefix}{name}::"), out)?;
        } else if let Some(stem) = name.strip_suffix(".cheby") {
            out.push((format!("{prefix}{stem}"), path));
        }
    }
    Ok(())
}
