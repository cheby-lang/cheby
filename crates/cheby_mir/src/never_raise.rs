//! The std kernels that never raise (D-735, D-767): a foreign call of one
//! of them gets no unwind edge ([`crate::unwind::rvalue_may_unwind`]).
//!
//! This crate does not depend on the runtime, so the list lives here. The
//! runtime's test `never_raise_table_matches` reads this file at run time
//! and requires every symbol to be on its `NEVER_UNWINDS` list (each
//! entry point there is checked to be one that never unwinds, D-697) and
//! none to be a kernel that can suspend: after cancellation (D-688) a
//! kernel that parks can raise. Only kernels that `NEVER_UNWINDS` names
//! by their exported symbol are listed; the integer and float kernels
//! generated by macros are named there by their Rust function, so they
//! are not.

/// Std kernels whose foreign calls get no unwind edge (D-735, D-767). Each never
/// raises: it is on the runtime's `NEVER_UNWINDS` list, which `never_raise_table_matches` checks.
/// No kernel that can suspend may be listed: it can raise a cancellation (D-688).
pub const NEVER_RAISE_KERNELS: &[&str] = &[
    "cheby_bytes_get",
    "cheby_bytes_json_plain_end",
    "cheby_bytes_length",
    "cheby_bytes_read_i8",
    "cheby_io_eprint",
    "cheby_io_eprintln",
    "cheby_io_print",
    "cheby_io_println",
    "cheby_list_length",
    "cheby_map_is_empty",
    "cheby_map_new",
    "cheby_map_size",
    "cheby_set_is_empty",
    "cheby_set_new",
    "cheby_set_size",
    "cheby_string_contains",
    "cheby_string_ends_with",
    "cheby_string_grapheme_length",
    "cheby_string_length",
    "cheby_string_starts_with",
];

/// Whether a foreign call of `symbol` never raises: `symbol` is in
/// [`NEVER_RAISE_KERNELS`].
#[must_use]
pub fn never_raises(symbol: &str) -> bool {
    NEVER_RAISE_KERNELS.binary_search(&symbol).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The table is sorted without duplicates, so `never_raises` can
    /// search it, and lists only std kernels: never a runtime helper
    /// (`CallRuntime` has its own rule) and never a kernel that can suspend
    /// and so raise a cancellation (D-688).
    #[test]
    fn the_table_is_sorted_and_lists_only_kernels_that_cannot_suspend() {
        assert!(
            NEVER_RAISE_KERNELS.windows(2).all(|w| w[0] < w[1]),
            "{NEVER_RAISE_KERNELS:?}"
        );
        for symbol in NEVER_RAISE_KERNELS {
            assert!(symbol.starts_with("cheby_"), "{symbol}");
            for suspends in [
                "cheby_rt_",
                "cheby_channel_",
                "cheby_fiber_",
                "cheby_scope_",
            ] {
                assert!(!symbol.starts_with(suspends), "{symbol}");
            }
            assert!(never_raises(symbol));
        }
        assert!(!never_raises("cheby_list_push"));
        assert!(!never_raises("cheby_channel_send"));
        assert!(!never_raises(""));
    }
}
