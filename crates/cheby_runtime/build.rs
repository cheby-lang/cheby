//! Computes the runtime ID (D-930) and writes `$OUT_DIR/runtime_id.rs`,
//! which `src/runtime_id.rs` includes: the ID as constants and the data
//! symbol `cheby_rt_id$<hex>` the runtime archive defines.
//!
//! It also passes the ID to the build scripts of direct dependents as
//! `DEP_CHEBY_RUNTIME_RUNTIME_ID` (`cargo::metadata`, which is why the
//! package declares `links = "cheby_runtime"`; nothing is linked through
//! it). `cheby_cli`'s build script puts it into the build ID (D-957).
//!
//! The hashing itself is in `build/runtime_id.rs`, which the tests include
//! too.

#[path = "build/runtime_id.rs"]
mod runtime_id;

use std::env;
use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

fn main() -> Result<(), Box<dyn Error>> {
    let crate_dir =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").ok_or("no CARGO_MANIFEST_DIR")?);
    let workspace_dir = crate_dir.join("..").join("..");
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").ok_or("no OUT_DIR")?);
    let target = env::var("TARGET")?;
    let mut features = Vec::new();
    let mut cfgs = Vec::new();
    for (key, value) in env::vars_os() {
        let Some(key) = key.to_str() else {
            continue;
        };
        if let Some(feature) = key.strip_prefix("CARGO_FEATURE_") {
            features.push(feature.to_ascii_lowercase());
        } else if let Some(cfg) = key.strip_prefix("CARGO_CFG_") {
            let cfg = cfg.to_ascii_lowercase();
            if runtime_id::CFGS.contains(&cfg.as_str()) {
                cfgs.push((cfg, value.to_string_lossy().into_owned()));
            }
        }
    }
    features.sort();
    cfgs.sort();
    // The settings, for the test that recomputes the ID
    // (`runtime_id_matches_the_build`).
    println!("cargo::rustc-env=CHEBY_RUNTIME_ID_TARGET={target}");
    println!(
        "cargo::rustc-env=CHEBY_RUNTIME_ID_FEATURES={}",
        features.join(";")
    );
    let cfg_list: Vec<String> = cfgs
        .iter()
        .map(|(name, value)| format!("{name}={value}"))
        .collect();
    println!(
        "cargo::rustc-env=CHEBY_RUNTIME_ID_CFGS={}",
        cfg_list.join(";")
    );
    let settings = runtime_id::Settings {
        target,
        features,
        cfgs,
    };
    let id = runtime_id::compute(&crate_dir, &workspace_dir, &settings)?;

    for dir in runtime_id::CRATE_DIRS {
        println!("cargo::rerun-if-changed={dir}");
    }
    for input in &id.inputs {
        println!("cargo::rerun-if-changed={}", input.display());
    }
    let hex = id.hex();
    println!("cargo::metadata=runtime_id={hex}");

    let mut bytes = String::new();
    for byte in id.id {
        write!(bytes, "0x{byte:02x}, ")?;
    }
    let bytes = bytes.trim_end_matches(", ");
    let source = format!(
        "// Generated by `crates/cheby_runtime/build.rs`: the runtime ID (D-930).

/// The runtime ID (D-930): SipHash-1-3 128 of the runtime's inputs,
/// computed by `build.rs`.
pub const RUNTIME_ID: [u8; 16] = [{bytes}];

/// [`RUNTIME_ID`] as 32 lowercase hex digits.
pub const RUNTIME_ID_HEX: &str = \"{hex}\";

/// The global data symbol the runtime archive defines (D-930):
/// `cheby_rt_id$` followed by [`RUNTIME_ID_HEX`]. Mach-O adds its leading
/// underscore.
pub const RUNTIME_ID_SYMBOL: &str = \"cheby_rt_id${hex}\";

/// The data behind [`RUNTIME_ID_SYMBOL`]: the ID's bytes. A program
/// object imports the symbol, so it links only against an archive built
/// from the same runtime (D-930).
#[used]
#[unsafe(export_name = \"cheby_rt_id${hex}\")]
static RUNTIME_ID_DATA: [u8; 16] = RUNTIME_ID;
"
    );
    fs::write(out_dir.join("runtime_id.rs"), source)?;
    Ok(())
}
