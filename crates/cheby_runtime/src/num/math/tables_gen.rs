//! Generates `tables.rs`, the constants and tables of the fast phase,
//! with [`Big`] at 256 bits, and checks that the file holds them.
//!
//! ```text
//! cargo test -p cheby_runtime num::math::tables_gen -- --ignored
//! ```
//!
//! regenerates the file (the test `tables_are_up_to_date` fails until it
//! is regenerated after a change here).

#![expect(
    clippy::arithmetic_side_effects,
    reason = "test code: index and bit arithmetic on small, known values"
)]

use std::fmt::Write as _;

use super::accurate;
use super::big::Big;
use super::fast::{Dd, LN_FIRST, LN_LAST};

/// The limbs of the computations (plus the accurate functions' two guard
/// limbs: 256 bits).
const PREC: usize = 2;

/// The nearest double-double to a `Big`.
fn nearest(value: &Big) -> Dd {
    let hi = value.round_f64(i64::MAX).unwrap();
    let rest = value.sub(&Big::from_f64(hi), value.limbs() + 1);
    Dd {
        hi,
        lo: rest.round_f64(i64::MAX).unwrap(),
    }
}

/// `x` with its last `drop` significand bits cleared.
fn truncated(x: f64, drop: u32) -> f64 {
    f64::from_bits(x.to_bits() & !((1_u64 << drop) - 1))
}

/// 64 bits as a Rust literal with `_` every four digits.
fn grouped(bits: u64) -> String {
    format!(
        "0x{:04x}_{:04x}_{:04x}_{:04x}",
        bits >> 48,
        (bits >> 32) & 0xffff,
        (bits >> 16) & 0xffff,
        bits & 0xffff
    )
}

/// The bits of a binary64 as a Rust literal.
fn hex(x: f64) -> String {
    grouped(x.to_bits())
}

fn dd(value: Dd) -> String {
    format!("Dd::bits({}, {})", hex(value.hi), hex(value.lo))
}

/// The text of `tables.rs`.
#[expect(clippy::too_many_lines, reason = "one section per table")]
fn render() -> String {
    let work = PREC + 2;
    let ln2 = accurate::ln2(work);
    let pi = accurate::pi(work + 1);
    let half_pi = pi.clone().shl(-1);
    let p1 = truncated(half_pi.round_f64(i64::MAX).unwrap(), 20);
    let rest = half_pi.sub(&Big::from_f64(p1), work);
    let p2 = truncated(rest.round_f64(i64::MAX).unwrap(), 20);
    let p3 = rest
        .sub(&Big::from_f64(p2), work)
        .round_f64(i64::MAX)
        .unwrap();
    let exp2 = |num: u64, den: u64| {
        let x = ln2.mul_u64(num, work).div_u64(den, work);
        nearest(&accurate::exp_big(&x, PREC))
    };
    let mut out = String::new();
    out.push_str(
        "//! The constants and tables of the fast phase (`fast.rs`): double-doubles\n\
         //! nearest to values computed with `Big` at 256 bits.\n\
         //!\n\
         //! Generated by `tables_gen.rs`; do not edit. Regenerate with\n\
         //! `cargo test -p cheby_runtime num::math::tables_gen -- --ignored`.\n\n\
         use super::fast::Dd;\n\n",
    );
    let _ = writeln!(
        out,
        "/// ln 2.\npub(super) const LN2: Dd = {};\n",
        dd(nearest(&ln2))
    );
    let _ = writeln!(
        out,
        "/// π/2.\npub(super) const HALF_PI: Dd = {};\n",
        dd(nearest(&half_pi))
    );
    let _ = writeln!(
        out,
        "/// π.\npub(super) const PI: Dd = {};\n",
        dd(nearest(&pi))
    );
    let _ = writeln!(
        out,
        "/// π/2 as 33 bits, 33 bits and the rest (Cody and Waite).\n\
         pub(super) const HALF_PI_PARTS: [f64; 3] = [\n    \
         f64::from_bits({}),\n    f64::from_bits({}),\n    f64::from_bits({}),\n];\n",
        hex(p1),
        hex(p2),
        hex(p3)
    );
    let table = |out: &mut String, doc: &str, name: &str, entries: Vec<String>| {
        let _ = writeln!(
            out,
            "/// {doc}\npub(super) const {name}: [Dd; {}] = [",
            entries.len()
        );
        for entry in entries {
            let _ = writeln!(out, "    {entry},");
        }
        out.push_str("];\n\n");
    };
    table(
        &mut out,
        "2^(i/16), i from 0 to 15.",
        "EXP2_COARSE",
        (0..16).map(|i| dd(exp2(i, 16))).collect(),
    );
    table(
        &mut out,
        "2^(j/256), j from 0 to 15.",
        "EXP2_FINE",
        (0..16).map(|j| dd(exp2(j, 256))).collect(),
    );
    let reciprocals: Vec<f64> = (LN_FIRST..=LN_LAST)
        .map(|i| 1.0 / (1.0 + f64::from(i32::try_from(i).unwrap()) / 256.0))
        .collect();
    let _ = writeln!(
        out,
        "/// For i from {LN_FIRST} to {LN_LAST}: `c = 1/(1 + i/256)`, rounded.\n\
         pub(super) const LN_C: [f64; {}] = [",
        reciprocals.len()
    );
    for c in &reciprocals {
        let _ = writeln!(out, "    f64::from_bits({}),", hex(*c));
    }
    out.push_str("];\n\n");
    table(
        &mut out,
        "`-ln c` for each `c` of `LN_C`.",
        "LN",
        reciprocals
            .iter()
            .map(|&c| dd(nearest(&accurate::ln(c, PREC).neg())))
            .collect(),
    );
    let sin_cos: Vec<(Big, Big)> = (0..52_u32)
        .map(|j| accurate::sin_cos(f64::from(j) / 64.0, PREC))
        .collect();
    table(
        &mut out,
        "sin(j/64), j from 0 to 51.",
        "SIN",
        sin_cos.iter().map(|(s, _)| dd(nearest(s))).collect(),
    );
    table(
        &mut out,
        "cos(j/64), j from 0 to 51.",
        "COS",
        sin_cos.iter().map(|(_, c)| dd(nearest(c))).collect(),
    );
    table(
        &mut out,
        "atan(j/64), j from 0 to 64.",
        "ATAN",
        (0..=64_u32)
            .map(|j| {
                if j == 0 {
                    dd(Dd { hi: 0.0, lo: 0.0 })
                } else {
                    dd(nearest(&accurate::atan2(f64::from(j) / 64.0, 1.0, PREC)))
                }
            })
            .collect(),
    );
    let (pi, ln2) = accurate::computed_constants(accurate::CONST_LIMBS);
    for (name, doc, value) in [("PI", "π", &pi), ("LN2", "ln 2", &ln2)] {
        let (limbs, exp) = value.limbs_and_exp();
        let _ = writeln!(
            out,
            "/// The weight of the last bit of `{name}_LIMBS`.\npub(super) const {name}_EXP: i64 = {exp};\n"
        );
        let _ = writeln!(
            out,
            "/// {doc} to {} bits: the limbs of its significand, least significant first.\n\
             pub(super) const {name}_LIMBS: [u64; {}] = [",
            limbs.len() * 64,
            limbs.len()
        );
        for limb in limbs {
            let _ = writeln!(out, "    {},", grouped(*limb));
        }
        out.push_str("];\n\n");
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

/// The path of `tables.rs`.
fn path() -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src/num/math/tables.rs")
}

#[test]
fn tables_are_up_to_date() {
    let text = std::fs::read_to_string(path()).unwrap();
    assert!(
        text == render(),
        "tables.rs is stale: regenerate it with \
         `cargo test -p cheby_runtime num::math::tables_gen -- --ignored`"
    );
}

#[test]
#[ignore = "writes src/num/math/tables.rs"]
fn write_tables() {
    std::fs::write(path(), render()).unwrap();
}
